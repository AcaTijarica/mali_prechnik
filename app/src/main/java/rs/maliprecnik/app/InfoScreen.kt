@Composable
private fun ColumnScope.OptionalPublisherImage() {
    val context = LocalContext.current
    val publisherImageResourceId = context.resources.getIdentifier(
        "slika_izdavacha",
        "drawable",
        context.packageName
    )
    if (publisherImageResourceId == 0) return

    Image(
        painter = painterResource(publisherImageResourceId),
        contentDescription = "Издавач Александар Милошевић",
        modifier = Modifier
            .fillMaxWidth(0.72f)
            .align(Alignment.CenterHorizontally)
            .clip(RoundedCornerShape(8.dp)),
        contentScale = ContentScale.FillWidth
    )
}

